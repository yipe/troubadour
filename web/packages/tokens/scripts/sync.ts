// Regenerates tokens.css, src/classes.ts, src/rarity.ts, src/palette.ts and SOURCE.md from a DPRcalc
// checkout. Run with `pnpm -C web/packages/tokens sync`. CI never runs it: the output is committed.
import { execFileSync } from "node:child_process"
import { existsSync, readFileSync, writeFileSync } from "node:fs"
import { homedir } from "node:os"
import { dirname, join } from "node:path"
import { fileURLToPath, pathToFileURL } from "node:url"

const PKG = join(dirname(fileURLToPath(import.meta.url)), "..")
const DPR_DIR = process.env.DPR_DIR ?? join(homedir(), "src", "dpr")
const THEME_DIR = join(DPR_DIR, "packages", "ui", "src", "theme")

// Groups in output order. A declaration belongs to the first group it matches.
const GROUPS: { name: string; match: RegExp }[] = [
  { name: "gray", match: /^--gray-/ },
  { name: "blue", match: /^--blue-/ },
  { name: "red", match: /^--red-/ },
  { name: "green", match: /^--green-/ },
  { name: "orange", match: /^--orange-/ },
  { name: "purple", match: /^--purple-/ },
  { name: "bg", match: /^--color-bg-/ },
  { name: "fg", match: /^--color-fg-(?!on-success-btn$)/ },
  { name: "border", match: /^--color-border-/ },
  { name: "accent", match: /^--color-accent-/ },
  { name: "success", match: /^--color-success-/ },
  { name: "danger", match: /^--color-danger-/ },
  { name: "warning", match: /^--color-warning-/ },
  { name: "info", match: /^--color-info-/ },
  { name: "rarity", match: /^--color-rarity-/ },
  { name: "chart", match: /^--color-chart-/ },
  { name: "tooltip", match: /^--color-tooltip-/ },
  { name: "subtle-badge", match: /^--color-subtle-badge-/ },
  { name: "skeleton", match: /^--color-skeleton-/ },
  { name: "class-base", match: /^--class-.+-base$/ },
  { name: "class", match: /^--color-class-/ },
]
// Not an SRD class; users add classes like it in the app.
const EXCLUDED = /artificer/

const THEME_SELECTORS = [":root,[data-theme='dark']", "[data-theme='light']", "[data-theme='midnight']"]
const DARK = THEME_SELECTORS[0] as string

if (!existsSync(join(THEME_DIR, "tokens.css"))) {
  console.log("DPRcalc checkout not found; the committed files stay as they are")
  process.exit(0)
}

type Decl = { name: string; value: string }

const source = readFileSync(join(THEME_DIR, "tokens.css"), "utf8").replace(/\/\*[\s\S]*?\*\//g, "")
const blocks = new Map<string, Decl[]>()
for (const m of source.matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
  const selector = (m[1] as string).replace(/\s+/g, "")
  if (!THEME_SELECTORS.includes(selector)) continue
  const decls = (m[2] as string)
    .split(";")
    .map((d) => d.trim())
    .filter(Boolean)
    .map((d) => {
      const i = d.indexOf(":")
      return { name: d.slice(0, i).trim(), value: d.slice(i + 1).trim() }
    })
  blocks.set(selector, decls)
}
for (const s of THEME_SELECTORS) if (!blocks.has(s)) throw new Error(`theme block ${s} not found`)

const groupOf = (name: string) => (EXCLUDED.test(name) ? -1 : GROUPS.findIndex((g) => g.match.test(name)))

const dropped: string[] = []
const kept = new Map<string, Decl[]>()
// :root is the dark block, handled first: every theme inherits what it keeps (the class base colours
// are defined only there).
const rootNames = new Set<string>()
for (const selector of THEME_SELECTORS) {
  let decls = (blocks.get(selector) as Decl[]).filter((d) => groupOf(d.name) >= 0)
  // A declaration whose var() points at something not kept would be broken; drop it, repeat until stable.
  for (;;) {
    const names = new Set([...rootNames, ...decls.map((d) => d.name)])
    const next = decls.filter((d) =>
      [...d.value.matchAll(/var\((--[\w-]+)/g)].every((r) => names.has(r[1] as string)),
    )
    if (next.length === decls.length) break
    for (const d of decls) if (!next.includes(d)) dropped.push(`${selector} ${d.name}: ${d.value}`)
    decls = next
  }
  // Array.sort is stable, so the source order holds within a group.
  if (selector === DARK) for (const d of decls) rootNames.add(d.name)
  kept.set(
    selector,
    [...decls].sort((a, b) => groupOf(a.name) - groupOf(b.name)),
  )
}

const sha = execFileSync("git", ["-C", DPR_DIR, "rev-parse", "HEAD"], { encoding: "utf8" }).trim()
const css =
  `/* Generated by scripts/sync.ts from DPRcalc ${sha}. Don't edit. */\n\n` +
  THEME_SELECTORS.map(
    (s) =>
      `${s.replace(",", ",\n")} {\n${(kept.get(s) as Decl[]).map((d) => `  ${d.name}: ${d.value};`).join("\n")}\n}\n`,
  ).join("\n")
writeFileSync(join(PKG, "tokens.css"), css)

const dark = kept.get(DARK) as Decl[]
const withPrefix = (prefix: string, suffix = "") =>
  dark
    .filter((d) => d.name.startsWith(prefix) && d.name.endsWith(suffix))
    .map((d) => ({ key: d.name.slice(prefix.length, d.name.length - suffix.length), value: d.value }))

const classes = withPrefix("--class-", "-base")
const rarities = withPrefix("--color-rarity-")
const cap = (s: string) => s.charAt(0).toUpperCase() + s.slice(1)

const header = "// Generated by scripts/sync.ts. Don't edit.\n"
writeFileSync(
  join(PKG, "src", "classes.ts"),
  `${header}
export const CLASS_NAMES = [${classes.map((c) => JSON.stringify(c.key)).join(", ")}] as const

export type DndClass = (typeof CLASS_NAMES)[number]

export const CLASS_LABELS: Record<DndClass, string> = {
${classes.map((c) => `  ${c.key}: ${JSON.stringify(cap(c.key))},`).join("\n")}
}

/** Identity colour of each class, the same in every theme. */
export const CLASS_BASE_COLORS: Record<DndClass, string> = {
${classes.map((c) => `  ${c.key}: ${JSON.stringify(c.value)},`).join("\n")}
}

/** The theme-resolved colour as a CSS value. */
export function classColorVar(c: DndClass): string {
  return \`var(--color-class-\${c})\`
}
`,
)

writeFileSync(
  join(PKG, "src", "rarity.ts"),
  `${header}
export const RARITIES = [${rarities.map((r) => JSON.stringify(r.key)).join(", ")}] as const

export type Rarity = (typeof RARITIES)[number]

export function rarityColorVar(r: Rarity): string {
  return \`var(--color-rarity-\${r})\`
}
`,
)

const pal = (await import(pathToFileURL(join(THEME_DIR, "postChartPalette.ts")).href)) as {
  POST_CHART_HUES: readonly string[]
  POST_CHART_PALETTE: Record<string, Record<string, string>>
  POST_CHART_COLOR_NAMES: Record<string, string>
}
const shades = Object.keys(pal.POST_CHART_PALETTE[pal.POST_CHART_HUES[0] as string] as object)
writeFileSync(
  join(PKG, "src", "palette.ts"),
  `${header}
export const SWATCH_HUES = ${JSON.stringify(pal.POST_CHART_HUES)} as const

export type SwatchHue = (typeof SWATCH_HUES)[number]

export const SWATCH_SHADES = ${JSON.stringify(shades)} as const

export type SwatchShade = (typeof SWATCH_SHADES)[number]

export const SWATCH_PALETTE: Record<SwatchHue, Record<SwatchShade, string>> = ${JSON.stringify(pal.POST_CHART_PALETTE)}

/** Display name keyed by hex, e.g. "Light Blue". */
export const SWATCH_NAMES: Record<string, string> = ${JSON.stringify(pal.POST_CHART_COLOR_NAMES)}
`,
)

const files = ["tokens.css", "src/classes.ts", "src/rarity.ts", "src/palette.ts"].map((f) => join(PKG, f))
execFileSync("pnpm", ["exec", "prettier", "--write", ...files], { cwd: PKG, stdio: "ignore" })

writeFileSync(
  join(PKG, "SOURCE.md"),
  `# Source

Generated by \`scripts/sync.ts\` from DPRcalc commit \`${sha}\`. Don't edit.

## Allow-list

${GROUPS.map((g) => `- \`${g.match.source}\``).join("\n")}

Excluded: anything matching \`${EXCLUDED.source}\`.

## Dropped (their \`var()\` target is not kept)

${dropped.length ? [...new Set(dropped)].map((d) => `- \`${d}\``).join("\n") : "None."}
`,
)
execFileSync("pnpm", ["exec", "prettier", "--write", join(PKG, "SOURCE.md")], { cwd: PKG, stdio: "ignore" })
console.log(
  `synced from DPRcalc ${sha.slice(0, 7)}; ${new Set(dropped).size} declarations dropped (see SOURCE.md)`,
)
