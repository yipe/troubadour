import { readFileSync } from "node:fs"
import { describe, expect, it } from "vitest"
import { CLASS_BASE_COLORS, CLASS_NAMES, classColorVar } from "./classes.ts"
import { SWATCH_HUES, SWATCH_NAMES, SWATCH_PALETTE, SWATCH_SHADES } from "./palette.ts"
import { RARITIES, rarityColorVar } from "./rarity.ts"

const css = readFileSync(new URL("../tokens.css", import.meta.url), "utf8")

function themeBlocks(): Record<string, Map<string, string>> {
  const out: Record<string, Map<string, string>> = {}
  for (const m of css.matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
    const selector = (m[1] as string).trim()
    const theme = /\[data-theme=["'](\w+)["']\]$/.exec(selector)?.[1]
    if (!theme) continue
    const decls = new Map<string, string>()
    for (const d of (m[2] as string).split(";")) {
      const i = d.indexOf(":")
      if (i > 0) decls.set(d.slice(0, i).trim(), d.slice(i + 1).trim())
    }
    out[theme] = decls
  }
  return out
}

const blocks = themeBlocks()

// Every token the Tailwind mapping in design-system.md reads, plus the class and rarity variables.
const REQUIRED = [
  ...["canvas", "surface", "subtle", "elevated"].map((k) => `--color-bg-${k}`),
  ...["default", "muted", "subtle", "on-accent"].map((k) => `--color-fg-${k}`),
  ...["default", "subtle", "strong"].map((k) => `--color-border-${k}`),
  ...["fg", "emphasis", "subtle"].map((k) => `--color-accent-${k}`),
  ...["success", "warning", "danger", "info"].flatMap((s) =>
    ["fg", "bg", "subtle"].map((k) => `--color-${s}-${k}`),
  ),
  "--color-subtle-badge-bg",
  "--color-subtle-badge-fg",
  "--color-tooltip-bg",
  "--color-tooltip-border",
  ...CLASS_NAMES.map((c) => `--color-class-${c}`),
  ...RARITIES.map((r) => `--color-rarity-${r}`),
]

describe("tokens.css", () => {
  it("has the three themes", () => {
    expect(Object.keys(blocks).sort()).toEqual(["dark", "light", "midnight"])
  })

  it.each(["dark", "light", "midnight"])("%s defines every required token", (theme) => {
    const block = blocks[theme] as Map<string, string>
    expect(REQUIRED.filter((k) => !block.has(k))).toEqual([])
  })

  it("has no comment other than the header, and no artificer", () => {
    expect(css.match(/\/\*/g)).toHaveLength(1)
    expect(css.startsWith("/* Generated by scripts/sync.ts")).toBe(true)
    expect(css).not.toContain("artificer")
  })
})

describe("classes", () => {
  it("has the 12 SRD classes", () => {
    expect(CLASS_NAMES).toHaveLength(12)
  })

  it.each(CLASS_NAMES)("%s base colour matches the dark block", (c) => {
    expect(CLASS_BASE_COLORS[c]).toBe((blocks.dark as Map<string, string>).get(`--class-${c}-base`))
  })

  it("builds the resolved-colour variable", () => {
    expect(classColorVar("bard")).toBe("var(--color-class-bard)")
    expect(rarityColorVar("veryrare")).toBe("var(--color-rarity-veryrare)")
  })
})

describe("palette", () => {
  it("has light, medium and dark hex values for every hue", () => {
    expect(Object.keys(SWATCH_PALETTE)).toHaveLength(SWATCH_HUES.length)
    for (const hue of SWATCH_HUES) {
      for (const shade of SWATCH_SHADES) expect(SWATCH_PALETTE[hue][shade]).toMatch(/^#[0-9a-f]{6}$/i)
    }
  })

  it("names every swatch", () => {
    for (const hue of SWATCH_HUES) {
      for (const shade of SWATCH_SHADES) expect(SWATCH_NAMES[SWATCH_PALETTE[hue][shade]]).toBeTruthy()
    }
  })
})
